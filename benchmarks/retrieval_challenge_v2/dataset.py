def validate_dataset() -> None:
    """Check dataset structure and relevance references."""
    memory_ids = [item[0] for item in MEMORIES]

    if len(memory_ids) != len(set(memory_ids)):
        raise ValueError("Memory IDs must be unique.")

    if len(QUERIES) != 8:
        raise ValueError("Expected exactly 8 queries.")

    if len(MEMORIES) != 16:
        raise ValueError("Expected exactly 16 memories.")

    known_ids = set(memory_ids)

    for name, category, query, relevant_ids in QUERIES:
        if not isinstance(relevant_ids, tuple) or not relevant_ids:
            raise ValueError(f"{name} must have one or more relevance labels.")
        if not set(relevant_ids).issubset(known_ids):
            raise ValueError(f"{name} references an unknown memory ID.")
        if len(relevant_ids) != len(set(relevant_ids)):
            raise ValueError(f"{name} contains duplicate relevance labels.")
        if not query.strip():
            raise ValueError(f"{name} has an empty query.")

